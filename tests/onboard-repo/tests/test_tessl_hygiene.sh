#!/usr/bin/env bash
# Outcome-based tests for tessl-hygiene.sh: pins jbaruch/* deps to latest and
# ensures the .gitignore block, without touching third-party pins or the
# committed AGENTS.md/CLAUDE.md/GEMINI.md entrypoints.
#
# Each case builds a throwaway git repo (the script requires a worktree) — no
# shared mutable state, order-independent.
#
# Run: bash skills/onboard-repo/tests/test_tessl_hygiene.sh
set -uo pipefail

SCRIPT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../skills/onboard-repo" && pwd)/tessl-hygiene.sh"

cleanup() { [[ -n "${TMP:-}" ]] && ! rm -rf "$TMP" && echo "warn: could not remove $TMP" >&2; return 0; }
pass() { PASS=$((PASS+1)); }
fail() { FAIL=$((FAIL+1)); echo "  ✗ FAIL: $1" >&2; }
mkrepo() {
  if ! { git init -q "$1" && ( cd "$1" && git config user.email t@t && git config user.name t ); }; then
    echo "fatal: cannot create test repo $1" >&2
    exit 2
  fi
}
# A fixture that fails to write would make its case test nothing; stop the run instead.
setup_fail() { echo "fatal: test setup failed: $1" >&2; exit 2; }

# Tessl's per-folder .gitignore files; the block must list every one.
FOLDER_IGNORES=(.claude/skills/.gitignore .codex/skills/.gitignore .cursor/rules/.gitignore
  .cursor/skills/.gitignore .github/skills/.gitignore .vscode/skills/.gitignore)
has_folder_ignores() { local f; for f in "${FOLDER_IGNORES[@]}"; do grep -qxF "$f" "$1" || return 1; done; }

# The block exactly as onboarded repos carry it before the per-folder entries.
old_block() {
  cat <<'EOF'
# === Tessl-generated artifacts (managed by jbaruch/coding-policy) ===
# Regenerated by `tessl install` (analogous to node_modules). Only tessl.json
# (the manifest) is committed; everything below is per-developer / per-agent
# output. AGENTS.md / CLAUDE.md / GEMINI.md are NOT ignored — tessl appends to
# them and they don't churn. Shared dirs (.github, .vscode) keep everything else;
# only tessl's own paths are listed.
.tessl/
.agents/
.mcp.json
.claude/settings.json
.claude/skills/tessl__*
.codex/config.toml
.codex/skills/tessl__*
.gemini/settings.json
.cursor/mcp.json
.cursor/hooks.json
.cursor/rules/tessl__*
.cursor/skills/tessl__*
.openhands/hooks.json
.openhands/skills/tessl-*
.github/mcp.json
.github/hooks/tessl.json
.github/skills/tessl__*
.vscode/mcp.json
.vscode/skills/tessl__*
# === end Tessl-generated artifacts ===
EOF
}

main() {
  [[ -f "$SCRIPT" && -r "$SCRIPT" ]] || { echo "fatal: script not found at $SCRIPT" >&2; exit 2; }
  command -v jq  >/dev/null 2>&1 || { echo "fatal: jq required"  >&2; exit 2; }
  command -v git >/dev/null 2>&1 || { echo "fatal: git required" >&2; exit 2; }

  TMP="$(mktemp -d)" || { echo "fatal: mktemp" >&2; exit 2; }
  trap cleanup EXIT
  FAIL=0; PASS=0

  local d out rc cp_ver react_ver

  # 1. pins jbaruch/* to latest, leaves third-party pins untouched.
  d="$TMP/1"; mkrepo "$d"
  cat > "$d/tessl.json" <<'JSON' || setup_fail "case 1 tessl.json"
{
  "name": "jbaruch/x",
  "mode": "vendored",
  "dependencies": {
    "jbaruch/coding-policy": { "version": "0.3.99" },
    "tessl/npm-react": { "version": "19.2.0" }
  }
}
JSON
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  cp_ver=$(jq -r '.dependencies["jbaruch/coding-policy"].version' "$d/tessl.json")
  react_ver=$(jq -r '.dependencies["tessl/npm-react"].version' "$d/tessl.json")
  if [[ $rc -eq 0 && "$cp_ver" == "latest" && "$react_ver" == "19.2.0" ]] \
     && printf '%s' "$out" | jq -e '.tessl_json=="pinned-latest"' >/dev/null; then pass
  else fail "pin: cp=$cp_ver react=$react_ver out=$out"; fi

  # 2. idempotent: already latest -> unchanged.
  d="$TMP/2"; mkrepo "$d"
  printf '{"dependencies":{"jbaruch/coding-policy":{"version":"latest"}}}\n' > "$d/tessl.json" || setup_fail "case 2 tessl.json"
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.tessl_json=="unchanged"' >/dev/null; then pass; else fail "idempotent pin: rc=$rc $out"; fi

  # 3. .gitignore created with the block when absent; AGENTS/CLAUDE/GEMINI NOT in it.
  d="$TMP/3"; mkrepo "$d"
  printf '{"dependencies":{}}\n' > "$d/tessl.json" || setup_fail "case 3 tessl.json"
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="created"' >/dev/null \
     && grep -qF '.tessl/' "$d/.gitignore" \
     && grep -qF '.gemini/settings.json' "$d/.gitignore" \
     && has_folder_ignores "$d/.gitignore" \
     && ! grep -qxF 'AGENTS.md' "$d/.gitignore" \
     && ! grep -qxF 'CLAUDE.md' "$d/.gitignore" \
     && ! grep -qxF 'GEMINI.md' "$d/.gitignore"; then pass
  else fail "gitignore created/content: $out"; fi

  # 4. appends to an existing .gitignore lacking the marker, preserving prior lines.
  d="$TMP/4"; mkrepo "$d"
  printf '{"dependencies":{}}\n' > "$d/tessl.json" || setup_fail "case 4 tessl.json"
  printf 'node_modules/\n' > "$d/.gitignore" || setup_fail "case 4 .gitignore"
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="appended"' >/dev/null \
     && grep -qxF 'node_modules/' "$d/.gitignore" \
     && grep -qF '.tessl/' "$d/.gitignore"; then pass
  else fail "gitignore append: $out"; fi

  # 5. unchanged when the marker is already present.
  d="$TMP/5"; mkrepo "$d"
  printf '{"dependencies":{}}\n' > "$d/tessl.json" || setup_fail "case 5 tessl.json"
  if ! (cd "$d" && bash "$SCRIPT" >/dev/null 2>&1); then fail "case 5 setup: first run failed"; else
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?  # second run
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="unchanged"' >/dev/null; then pass; else fail "gitignore idempotent: rc=$rc $out"; fi
  fi

  # 6. missing tessl.json -> tessl_json:absent, gitignore still written.
  d="$TMP/6"; mkrepo "$d"
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.tessl_json=="absent" and .gitignore=="created"' >/dev/null; then pass
  else fail "absent tessl.json: rc=$rc out=$out"; fi

  # 7. an old block is rewritten in place to the current one; lines around it survive.
  d="$TMP/7"; mkrepo "$d"
  printf '{"dependencies":{}}\n' > "$d/tessl.json" || setup_fail "case 7 tessl.json"
  { printf 'node_modules/\n' && old_block && printf 'dist/\n'; } > "$d/.gitignore" || setup_fail "case 7 .gitignore"
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="updated"' >/dev/null \
     && has_folder_ignores "$d/.gitignore" \
     && [[ "$(head -n 1 "$d/.gitignore")" == "node_modules/" ]] \
     && [[ "$(tail -n 1 "$d/.gitignore")" == "dist/" ]] \
     && [[ "$(grep -cF '=== Tessl-generated artifacts' "$d/.gitignore")" == "1" ]]; then pass
  else fail "old block refresh: $out"; fi

  # 8. a second run after the refresh reports unchanged and leaves the bytes alone.
  d="$TMP/8"; mkrepo "$d"
  local before="" after=""
  if ! { printf 'node_modules/\n' && old_block; } > "$d/.gitignore"; then fail "case 8 setup: fixture write failed"
  elif ! (cd "$d" && bash "$SCRIPT" >/dev/null 2>&1); then fail "case 8 setup: first refresh failed"
  elif ! before=$(cat "$d/.gitignore") || [[ -z "$before" ]]; then fail "case 8 setup: snapshot read failed"
  else
    out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
    if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="unchanged"' >/dev/null \
       && after=$(cat "$d/.gitignore") && [[ "$after" == "$before" ]]; then pass
    else fail "current block unchanged: rc=$rc $out"; fi
  fi

  # 9. a block missing its end marker fails and is left untouched.
  d="$TMP/9"; mkrepo "$d"
  if old_block | sed '$d' > "$d/.gitignore" && before=$(cat "$d/.gitignore") && [[ -n "$before" ]]; then
    out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
    if [[ $rc -ne 0 ]] && after=$(cat "$d/.gitignore") && [[ "$after" == "$before" ]]; then pass
    else fail "missing end marker: rc=$rc out=$out"; fi
  else fail "case 9 setup: fixture write or snapshot failed"; fi

  # 10. two start markers fail and are left untouched.
  d="$TMP/10"; mkrepo "$d"
  if { old_block && old_block; } > "$d/.gitignore" && before=$(cat "$d/.gitignore") && [[ -n "$before" ]]; then
    out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
    if [[ $rc -ne 0 ]] && after=$(cat "$d/.gitignore") && [[ "$after" == "$before" ]]; then pass
    else fail "duplicate start marker: rc=$rc out=$out"; fi
  else fail "case 10 setup: fixture write or snapshot failed"; fi

  # 11. a CRLF .gitignore carrying the old block refreshes, then settles to unchanged.
  d="$TMP/11"; mkrepo "$d"
  { printf 'node_modules/\n' && old_block; } | sed 's/$/\r/' > "$d/.gitignore" || setup_fail "case 11 .gitignore"
  out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
  if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="updated"' >/dev/null && has_folder_ignores "$d/.gitignore"; then
    out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
    if [[ $rc -eq 0 ]] && printf '%s' "$out" | jq -e '.gitignore=="unchanged"' >/dev/null; then pass
    else fail "CRLF second run: rc=$rc $out"; fi
  else fail "CRLF refresh: rc=$rc $out"; fi

  # 12. a valid block plus another line carrying the marker fails and is left untouched.
  d="$TMP/12"; mkrepo "$d"
  if { old_block && printf 'see # === Tessl-generated artifacts (managed by jbaruch/coding-policy) === above\n'; } > "$d/.gitignore" \
     && before=$(cat "$d/.gitignore") && [[ -n "$before" ]]; then
    out="$(cd "$d" && bash "$SCRIPT" 2>/dev/null)"; rc=$?
    if [[ $rc -ne 0 ]] && after=$(cat "$d/.gitignore") && [[ "$after" == "$before" ]]; then pass
    else fail "embedded marker: rc=$rc out=$out"; fi
  else fail "case 12 setup: fixture write or snapshot failed"; fi

  echo "─────────────────────────────────────────────" >&2
  if [[ $FAIL -gt 0 ]]; then echo "FAILED: ${FAIL} failed, ${PASS} passed" >&2; exit 1; fi
  echo "PASSED: all ${PASS} checks" >&2
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
